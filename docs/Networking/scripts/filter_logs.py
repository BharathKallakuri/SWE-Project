def parse_cli_timestamp(val: Optional[str]) -> Optional[datetime.datetime]:
    if not val:
        return None
    val = val.strip().replace("T", " ")
    if " IST" in val:
        val = val.replace(" IST", "")
    for fmt in ("%Y-%m-%d %H:%M:%S.%f", "%Y-%m-%d %H:%M:%S", "%Y-%m-%d"):
        try:
            dt = datetime.datetime.strptime(val, fmt)
            return dt.replace(tzinfo=IST_TZ)
        except ValueError:
            pass
    print(f"Warning: Could not parse timestamp '{val}'. Ignored.", file=sys.stderr)
    return None


def main():
    parser = build_arg_parser()
    args = parser.parse_args()

    files_to_read: List[str] = []
    using_stdin = False

    if not sys.stdin.isatty() and not args.file:
        using_stdin = True
    elif args.file:
        for pattern in args.file:
            if pattern == "-":
                using_stdin = True
            else:
                matches = glob.glob(pattern)
                if matches:
                    files_to_read.extend(matches)
                elif os.path.exists(pattern):
                    files_to_read.append(pattern)
                else:
                    print(f"Warning: File pattern not found: {pattern}", file=sys.stderr)
    else:
        defaults = find_default_log_files()
        if defaults:
            print(f"[filter_logs] Auto-detected latest log file: {defaults[0]}", file=sys.stderr)
            files_to_read.append(defaults[0])
        else:
            print(
                "Error: No log file specified and no default PawPatrol log files found in %LOCALAPPDATA%\\PawPatrol.\n"
                "Please specify a log file with -f / --file or pipe logs via stdin.",
                file=sys.stderr
            )
            sys.exit(1)

    all_entries: List[LogEntry] = []

    if using_stdin:
        all_entries.extend(parse_log_stream(sys.stdin))

    for filepath in files_to_read:
        try:
            with open(filepath, "r", encoding="utf-8", errors="replace") as f:
                all_entries.extend(parse_log_stream(f))
        except Exception as e:
            print(f"Error reading {filepath}: {e}", file=sys.stderr)

    if not all_entries:
        print("No log entries found in input.", file=sys.stderr)
        sys.exit(0)

    if args.list_modules:
        report = list_modules_report(all_entries)
        print(report)
        sys.exit(0)

    # If --to-ist or --all is passed, include all modules automatically
    match_all_modules = args.to_ist or args.all
    if not match_all_modules:
        raw_modules = args.module or []
        target_modules = [m.strip() for raw in raw_modules for m in raw.split(",") if m.strip()]
        match_all_modules = any(m.lower() in ("all", "*") for m in target_modules)
    else:
        target_modules = []

    start_time = parse_cli_timestamp(args.start)
    end_time = parse_cli_timestamp(args.end)

    matched_entries: List[LogEntry] = []
    for entry in all_entries:
        if not match_all_modules:
            if not entry.matches_module(target_modules, exact=args.exact):
                continue
        if not entry.matches_level(args.level, args.min_level):
            continue
        if not entry.matches_grep(args.grep, ignore_case=not args.case_sensitive):
            continue
        if not entry.matches_time(start_time, end_time):
            continue
        matched_entries.append(entry)

    if args.json:
        data = [e.to_dict() for e in matched_entries]
        output_str = json.dumps(data, indent=2)
    elif args.clean:
        output_str = "\n".join(e.to_clean_string() for e in matched_entries)
    elif args.raw:
        if args.to_ist:
            # Keep raw prefix, convert UTC to IST
            output_str = "\n".join(e.to_raw_with_ist() for e in matched_entries)
        else:
            # Unstripped raw lines
            output_str = "\n".join(e.raw_text for e in matched_entries)
    else:
        # Default: stripped prefix with IST timestamp
        output_str = "\n".join(
            e.to_stripped_text(
                include_datetime=not args.no_datetime,
                inline_timestamp=args.timestamp,
                with_level=args.with_level,
                pure_ist=args.to_ist
            )
            for e in matched_entries
        )

    if args.stats:
        stats_header = (
            f"\n--- Statistics: {len(matched_entries)} / {len(all_entries)} entries matched ---"
        )
        output_str = output_str + "\n" + stats_header if output_str else stats_header

    # Determine destination
    destination_file = args.output
    if args.in_place:
        if len(files_to_read) == 1:
            destination_file = files_to_read[0]
        else:
            print("Error: --in-place can only be used with a single file.", file=sys.stderr)
            sys.exit(1)

    if destination_file:
        try:
            with open(destination_file, "w", encoding="utf-8") as out_f:
                out_f.write(output_str + "\n")
            print(f"[filter_logs] Successfully wrote {len(matched_entries)} entries to {destination_file}", file=sys.stderr)
        except Exception as e:
            print(f"Error writing to {destination_file}: {e}", file=sys.stderr)
            sys.exit(1)
    else:
        if output_str:
            print(output_str)


if __name__ == "__main__":
    main()
