#!/usr/bin/env python3
"""
filter_logs.py - Filter and inspect application logs generated by FileTraceListener and project modules.

Features:
  1. Default Networking Filter: Filters for Networking logs, strips 'UX Information: 0 : ' prefix.
  2. Automatic UTC to IST Conversion: Automatically converts UTC timestamps (Z suffix) to IST (UTC+05:30).
  3. Convert-All Mode (--to-ist): Converts timestamps from UTC to IST for ALL logs in the file without filtering.
  4. Multi-Module & Search: Filter by any module (-m Chat, -m Whiteboard), log level, time range, or regex.
  5. Flexible Output Formats: Stripped (default), Inline Timestamp (-t), Clean (--clean), JSON (--json), or Raw (--raw).

Usage Examples:
    # 1. Convert all timestamps in the file from UTC to IST (all modules):
    python filter_logs.py -f app.log --to-ist

    # 2. Convert all timestamps to IST, keeping the raw 'UX Information: 0 : ' prefix:
    python filter_logs.py -f app.log --to-ist --raw

    # 3. Convert all timestamps to IST with inline timestamps:
    python filter_logs.py -f app.log --to-ist -t

    # 4. Save converted file to a new file:
    python filter_logs.py -f app.log --to-ist -o app_ist.log

    # 5. Overwrite file in-place with IST timestamps:
    python filter_logs.py -f app.log --to-ist -i

    # 6. Filter for Networking logs only (default):
    python filter_logs.py -f app.log

    # 7. Filter for another module (e.g. Chat):
    python filter_logs.py -f app.log -m Chat
"""

import argparse
import datetime
import glob
import json
import os
import re
import sys
from typing import List, Optional, Tuple, Dict, Any

# Indian Standard Time (IST): UTC + 5 hours 30 minutes
IST_TZ = datetime.timezone(datetime.timedelta(hours=5, minutes=30), name="IST")

# Regex to detect TraceListener header lines:
# Examples:
#   "UX Information: 0 : [Networking] CommunicatorFactory: Starting..."
#   "UX Information 0 : [Networking] ..."
#   "CopProject Error: 0 : [Networking] ..."
# Group 1: Source / Process name
# Group 2: Log Level (Information, Warning, Error, Critical, Verbose)
# Group 3: Event ID
# Group 4: Message body
TRACE_HEADER_REGEX = re.compile(
    r"^(\S.*?)\s+(Information|Warning|Error|Critical|Verbose)\s*:?\s*(\d+)\s*:\s*(.*)$",
    re.IGNORECASE
)

# Regex to detect DateTime metadata emitted by TextWriterTraceListener (TraceOptions.DateTime)
# Example: "    DateTime=2026-11-21T15:59:50.7586254Z"
TRACE_DATETIME_REGEX = re.compile(
    r"^\s*DateTime=([0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(?:\.[0-9]+)?Z?)\s*$",
    re.IGNORECASE
)

# Regex to extract bracketed module tags from the start of a message:
# Example: "[Networking]", "[Cloud.Networking]", "[Chat]", "[Whiteboard][LineState]"
MODULE_TAG_REGEX = re.compile(r"^\[([A-Za-z0-9_.-]+)\]")

# Generic timestamp prefix for other log types (e.g., "[2026-11-21 22:46:53 IST]" or "2026-11-21 15:59:50")
INLINE_TIMESTAMP_REGEX = re.compile(
    r"^\[?([0-9]{4}-[0-9]{2}-[0-9]{2}[ T][0-9]{2}:[0-9]{2}:[0-9]{2}(?:\.[0-9]+)?(?:\s*IST|Z)?)\]?\s*(.*)$",
    re.IGNORECASE
)

LEVEL_HIERARCHY = {
    "VERBOSE": 1,
    "DEBUG": 1,
    "INFORMATION": 2,
    "INFO": 2,
    "WARNING": 3,
    "WARN": 3,
    "ERROR": 4,
    "CRITICAL": 5,
    "FATAL": 5,
}


class LogEntry:
    def __init__(self, raw_lines: List[str]):
        self.raw_lines = raw_lines
        self.raw_text = "\n".join(raw_lines)
        self.source: Optional[str] = None
        self.level: Optional[str] = None
        self.event_id: Optional[int] = None
        self.first_line_message: str = ""
        self.message: str = ""
        self.timestamp: Optional[datetime.datetime] = None  # Stored in IST
        self.timestamp_str: Optional[str] = None
        self.raw_timestamp_str: Optional[str] = None
        self.modules: List[str] = []
        self._parse()

    def _parse(self):
        if not self.raw_lines:
            return

        first_line = self.raw_lines[0].strip()

        # Check for TraceListener format:
        trace_match = TRACE_HEADER_REGEX.match(first_line)
        if trace_match:
            self.source = trace_match.group(1).strip()
            self.level = trace_match.group(2).capitalize()
            try:
                self.event_id = int(trace_match.group(3))
            except ValueError:
                self.event_id = 0
            self.first_line_message = trace_match.group(4)
            self.message = trace_match.group(4)
        else:
            # Check for inline timestamp
            time_match = INLINE_TIMESTAMP_REGEX.match(first_line)
            if time_match:
                self.timestamp_str = time_match.group(1)
                self.raw_timestamp_str = self.timestamp_str
                self.first_line_message = time_match.group(2)
                self.message = time_match.group(2)
            else:
                self.first_line_message = first_line
                self.message = first_line

        # Inspect continuation lines for DateTime metadata and message body
        additional_message_lines = []
        for line in self.raw_lines[1:]:
            dt_match = TRACE_DATETIME_REGEX.match(line)
            if dt_match:
                self.raw_timestamp_str = dt_match.group(1)
                self.timestamp_str = dt_match.group(1)
            else:
                additional_message_lines.append(line)

        if additional_message_lines:
            if self.message:
                self.message += "\n" + "\n".join(additional_message_lines)
            else:
                self.message = "\n".join(additional_message_lines)

        # Parse timestamp string and convert UTC to IST
        if self.timestamp_str:
            self.timestamp = self._parse_to_ist(self.timestamp_str)

        # Extract module tags from message
        self.modules = self._extract_modules(self.message)

    @staticmethod
    def _parse_to_ist(dt_str: str) -> Optional[datetime.datetime]:
        """
        Parses ISO datetime string. If UTC (marked with Z or +00:00), automatically converts to IST.
        """
        s = dt_str.strip()
        is_utc = s.endswith("Z") or "+00:00" in s or "+0000" in s

        # Remove trailing Z or offset for parsing
        s_clean = s.rstrip("Z")
        if "+00:00" in s_clean:
            s_clean = s_clean.replace("+00:00", "")
        if " IST" in s_clean:
            s_clean = s_clean.replace(" IST", "")

        # Truncate fractional seconds beyond 6 digits
        s_clean = re.sub(r"(\.\d{6})\d+", r"\1", s_clean)
        s_clean = s_clean.replace("T", " ").strip()

        parts = s_clean.split(".")
        if len(parts) == 2:
            clean = parts[0] + "." + parts[1][:6].ljust(6, "0")
            fmt = "%Y-%m-%d %H:%M:%S.%f"
        else:
            clean = parts[0]
            fmt = "%Y-%m-%d %H:%M:%S"

        try:
            parsed = datetime.datetime.strptime(clean, fmt)
            if is_utc:
                # Convert UTC to IST (+05:30)
                parsed = parsed.replace(tzinfo=datetime.timezone.utc).astimezone(IST_TZ)
            else:
                parsed = parsed.replace(tzinfo=IST_TZ)
            return parsed
        except Exception:
            return None

    @staticmethod
    def _extract_modules(text: str) -> List[str]:
        """Extracts modules from bracket tags like [Networking], [Cloud.Networking], [Chat]"""
        modules = []
        first_line = text.strip().split("\n")[0]
        pos = 0
        while pos < len(first_line):
            m = re.match(r"\s*\[([A-Za-z0-9_.-]+)\]", first_line[pos:])
            if m:
                tag = m.group(1)
                modules.append(tag)
                pos += m.end()
            else:
                break
        return modules

    def matches_module(self, target_modules: List[str], exact: bool = False) -> bool:
        if not target_modules:
            return True

        for target in target_modules:
            target_norm = target.strip().lower()
            if not target_norm:
                continue

            for mod in self.modules:
                mod_norm = mod.lower()
                if exact:
                    if mod_norm == target_norm:
                        return True
                else:
                    if target_norm in mod_norm or mod_norm in target_norm:
                        return True

            if not exact:
                if f"[{target_norm}]" in self.message.lower() or f"[{target_norm}." in self.message.lower():
                    return True

        return False

    def matches_level(self, level: Optional[str], min_level: Optional[str]) -> bool:
        if not level and not min_level:
            return True

        entry_level_norm = (self.level or "INFO").upper()
        entry_rank = LEVEL_HIERARCHY.get(entry_level_norm, 2)

        if level:
            target_rank = LEVEL_HIERARCHY.get(level.strip().upper(), -1)
            if entry_rank != target_rank:
                return False

        if min_level:
            min_rank = LEVEL_HIERARCHY.get(min_level.strip().upper(), 2)
            if entry_rank < min_rank:
                return False

        return True

    def matches_grep(self, pattern: Optional[str], ignore_case: bool = True) -> bool:
        if not pattern:
            return True
        flags = re.IGNORECASE if ignore_case else 0
        return bool(re.search(pattern, self.raw_text, flags=flags))

    def matches_time(self, start: Optional[datetime.datetime], end: Optional[datetime.datetime]) -> bool:
        if not self.timestamp:
            return True
        if start and self.timestamp < start:
            return False
        if end and self.timestamp > end:
            return False
        return True

    def to_stripped_text(
        self,
        include_datetime: bool = True,
        inline_timestamp: bool = False,
        with_level: bool = False,
        pure_ist: bool = False
    ) -> str:
        """
        Returns the log entry with the '<Process> <Level>: <EventId> :' prefix stripped.
        Retains stack traces, continuation lines, and converted IST timestamp metadata.
        """
        first_line = self.first_line_message

        prefix_parts = []
        if inline_timestamp:
            if self.timestamp:
                ts = self.timestamp.strftime("%Y-%m-%d %H:%M:%S") + " IST"
            elif self.timestamp_str:
                ts = self.timestamp_str
            else:
                ts = "-----------------------"
            prefix_parts.append(f"[{ts}]")

        if with_level:
            raw_lvl = (self.level or "INFO").upper()
            lvl = {
                "INFORMATION": "INFO",
                "WARNING": "WARN",
                "CRITICAL": "CRIT",
                "VERBOSE": "VERB",
            }.get(raw_lvl, raw_lvl)[:5]
            prefix_parts.append(f"[{lvl:5s}]")

        if prefix_parts:
            first_line = " ".join(prefix_parts) + " " + first_line

        output_lines = [first_line]
        for line in self.raw_lines[1:]:
            m_dt = TRACE_DATETIME_REGEX.match(line)
            if m_dt:
                if include_datetime and not inline_timestamp:
                    if self.timestamp:
                        ist_formatted = self.timestamp.strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
                        if pure_ist:
                            output_lines.append(f"    DateTime={ist_formatted} IST")
                        else:
                            output_lines.append(f"    DateTime={ist_formatted} IST (UTC: {m_dt.group(1)})")
                    else:
                        output_lines.append(line)
            else:
                output_lines.append(line)

        return "\n".join(output_lines)

    def to_raw_with_ist(self) -> str:
        """
        Preserves original raw header line ('UX Information: 0 : ...')
        while replacing UTC DateTime= line with converted IST timestamp.
        """
        output_lines = [self.raw_lines[0]]
        for line in self.raw_lines[1:]:
            m_dt = TRACE_DATETIME_REGEX.match(line)
            if m_dt and self.timestamp:
                ist_formatted = self.timestamp.strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
                output_lines.append(f"    DateTime={ist_formatted} IST")
            else:
                output_lines.append(line)
        return "\n".join(output_lines)

    def to_clean_string(self) -> str:
        """Formatted as: [TIMESTAMP IST] [LEVEL] [MODULE] Message"""
        if self.timestamp:
            ts = self.timestamp.strftime("%Y-%m-%d %H:%M:%S") + " IST"
        elif self.timestamp_str:
            ts = self.timestamp_str
        else:
            ts = "-----------------------"

        raw_lvl = (self.level or "INFO").upper()
        lvl = {
            "INFORMATION": "INFO",
            "WARNING": "WARN",
            "CRITICAL": "CRIT",
            "VERBOSE": "VERB",
        }.get(raw_lvl, raw_lvl)[:5]

        mod = f"[{self.modules[0]}]" if self.modules else ""
        msg = self.first_line_message
        if self.modules:
            for m in self.modules:
                prefix = f"[{m}]"
                if msg.startswith(prefix):
                    msg = msg[len(prefix):].lstrip()
        first_line = f"[{ts}] [{lvl:5s}] {mod} {msg}".rstrip()

        output_lines = [first_line]
        for line in self.raw_lines[1:]:
            if not TRACE_DATETIME_REGEX.match(line):
                output_lines.append(line)
        return "\n".join(output_lines)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "source": self.source,
            "level": self.level,
            "eventId": self.event_id,
            "timestampUtc": self.raw_timestamp_str,
            "timestampIst": self.timestamp.strftime("%Y-%m-%d %H:%M:%S.%f")[:-3] + " IST" if self.timestamp else None,
            "modules": self.modules,
            "message": self.message,
            "raw": self.raw_text
        }


def parse_log_stream(stream) -> List[LogEntry]:
    """Parses a stream of lines into discrete LogEntry objects."""
    entries: List[LogEntry] = []
    current_lines: List[str] = []

    def is_new_entry_start(line: str) -> bool:
        if TRACE_HEADER_REGEX.match(line):
            return True
        if INLINE_TIMESTAMP_REGEX.match(line):
            return True
        if MODULE_TAG_REGEX.match(line) and not line.startswith((" ", "\t")):
            return True
        return False

    for line in stream:
        line_clean = line.rstrip("\r\n")

        if not current_lines:
            if not line_clean.strip():
                continue
            current_lines.append(line_clean)
            continue

        if is_new_entry_start(line_clean):
            entries.append(LogEntry(current_lines))
            current_lines = [line_clean]
        else:
            current_lines.append(line_clean)

    if current_lines:
        entries.append(LogEntry(current_lines))

    return entries


def find_default_log_files() -> List[str]:
    """Finds PawPatrol log files in standard locations."""
    candidates = []

    # 1. %LOCALAPPDATA%\PawPatrol
    local_app_data = os.environ.get("LOCALAPPDATA", "")
    if local_app_data:
        pawpatrol_dir = os.path.join(local_app_data, "PawPatrol")
        if os.path.isdir(pawpatrol_dir):
            txt_files = glob.glob(os.path.join(pawpatrol_dir, "PawPatrol-*.txt"))
            originals = [f for f in txt_files if not f.endswith("-read.txt")]
            candidates.extend(originals if originals else txt_files)

    # 2. Workspace directories / current directory
    workspace_logs = glob.glob("**/PawPatrol-*.txt", recursive=True)
    candidates.extend(workspace_logs)

    # 3. Near the script itself or parent directories
    script_dir = os.path.dirname(os.path.abspath(__file__))
    candidates.extend(glob.glob(os.path.join(script_dir, "**", "PawPatrol-*.txt"), recursive=True))
    candidates.extend(glob.glob(os.path.join(script_dir, "..", "**", "PawPatrol-*.txt"), recursive=True))

    # Sort by modification time, newest first
    candidates = sorted(list(set(candidates)), key=lambda p: os.path.getmtime(p), reverse=True)
    return candidates


def list_modules_report(entries: List[LogEntry]) -> str:
    """Generates a summary of all modules discovered in the logs."""
    stats: Dict[str, Dict[str, int]] = {}
    unassigned_count = 0

    for entry in entries:
        if not entry.modules:
            unassigned_count += 1
            continue
        for mod in entry.modules:
            if mod not in stats:
                stats[mod] = {"TOTAL": 0, "INFO": 0, "WARN": 0, "ERROR": 0, "OTHER": 0}
            stats[mod]["TOTAL"] += 1
            lvl = (entry.level or "INFO").upper()
            if "WARN" in lvl:
                stats[mod]["WARN"] += 1
            elif "ERR" in lvl or "CRIT" in lvl:
                stats[mod]["ERROR"] += 1
            elif "INFO" in lvl:
                stats[mod]["INFO"] += 1
            else:
                stats[mod]["OTHER"] += 1

    lines = [
        "=" * 70,
        f"{'MODULE':<35} | {'TOTAL':<7} | {'INFO':<6} | {'WARN':<6} | {'ERROR':<6}",
        "-" * 70,
    ]
    for mod in sorted(stats.keys()):
        m_stat = stats[mod]
        lines.append(
            f"{mod:<35} | {m_stat['TOTAL']:<7} | {m_stat['INFO']:<6} | {m_stat['WARN']:<6} | {m_stat['ERROR']:<6}"
        )
    if unassigned_count > 0:
        lines.append(f"{'[No Module Tag / System]':<35} | {unassigned_count:<7} | {'-':<6} | {'-':<6} | {'-':<6}")
    lines.append("=" * 70)
    return "\n".join(lines)


